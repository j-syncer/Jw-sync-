DESC = {
    "zh-Hans": "Simplified Chinese (Mandarin) copy for the static guide pages, keyed by slug.",
    "zh-Hant": "Traditional Chinese (Mandarin) copy for the static guide pages, keyed by slug.",
    "yue-Hant": "Cantonese copy for the static guide pages, keyed by slug.",
}


def q(s):
    """A Python string literal that keeps CJK readable in the source."""
    return json.dumps(s, ensure_ascii=False)


def render(guides, order):
    out = ["{\n"]
    for slug in order:
        g = guides[slug]
        out.append("\n %s: {\n" % q(slug))
        out.append("  %s: %s,\n" % (q("title"), q(g["title"])))
        out.append("  %s: %s,\n" % (q("h1"), q(g["h1"])))
        out.append("  %s: %s,\n" % (q("description"), q(g["description"])))
        out.append("  \"intro\": [\n")
        for p in g["intro"]:
            out.append("   %s,\n" % q(p))
        out.append("  ],\n")
        for field in ("steps", "sections", "faq"):
            out.append("  \"%s\": [\n" % field)
            for a, b in g[field]:
                out.append("   (%s, %s),\n" % (q(a), q(b)))
            out.append("  ],\n")
        out.append(" },\n")
    out.append("}\n")
    return "".join(out)


def convert_text(s):
    """Simplified → Traditional with the glossary pinned, not guessed."""
    parts, i = [], 0
    while i < len(s):
        for t in _TERMS_ORDER:
            if s.startswith(t, i):
                parts.append(("term", TERMS[t]))
                i += len(t)
                break
        else:
            if parts and parts[-1][0] == "prose":
                parts[-1] = ("prose", parts[-1][1] + s[i])
            else:
                parts.append(("prose", s[i]))
            i += 1
    out = "".join(v if k == "term" else CONV.convert(v) for k, v in parts)
    for a, b in POST.items():
        out = out.replace(a, b)
    return out


def convert(obj):
    if isinstance(obj, str):
        return convert_text(obj)
    if isinstance(obj, list):
        return [convert(x) for x in obj]
    if isinstance(obj, dict):
        return {k: convert(v) for k, v in obj.items()}
    return obj


def main():
    batch_dir = sys.argv[1]
    sys.path.insert(0, HERE)
    import build_guides
    order = [g["slug"] for g in build_guides.GUIDES]

    data = {"zh-Hans": {}, "yue-Hant": {}}
    for p in sorted(glob.glob(os.path.join(batch_dir, "b*.json"))):
        batch = json.load(io.open(p, encoding="utf-8"))
        for lang, guides in batch.items():
            for slug, g in guides.items():
                if slug in data[lang]:
                    sys.exit("ABORT: %s translated twice for %s" % (slug, lang))
                data[lang][slug] = g

    for lang in ("zh-Hans", "yue-Hant"):
        for slug, g in data[lang].items():
            for m in STRAY.finditer(json.dumps(g, ensure_ascii=False)):
                sys.exit("ABORT %s/%s: stray %r (U+%04X) in Chinese copy"
                         % (lang, slug, m.group(0), ord(m.group(0))))
        missing = [s for s in order if s not in data[lang]]
        extra = [s for s in data[lang] if s not in order]
        if extra:
            sys.exit("ABORT %s: unknown slug(s) %s" % (lang, extra))
        print("%-9s %2d/%d translated%s"
              % (lang, len(data[lang]), len(order),
                 "" if not missing else "  missing: " + ", ".join(missing)))

    # zh-Hant is the Simplified module converted, so it can never drift out of
    # step with the copy it mirrors — but a conversion that is wrong is worse
    # than one that is missing, so every banned form fails the build here.
    data["zh-Hant"] = convert(data["zh-Hans"])
    bad = []
    for slug, g in data["zh-Hant"].items():
        blob = json.dumps(g, ensure_ascii=False)
        for form in BANNED:
            if form in blob:
                bad.append("%s: %r" % (slug, form))
    if bad:
        sys.exit("ABORT: banned Traditional form(s) in the converted copy:\n  "
                 + "\n  ".join(sorted(set(bad))))

    for lang, fname, upper in (("zh-Hans", "guides_zh_hans.py", "ZH_HANS"),
                               ("zh-Hant", "guides_zh_hant.py", "ZH_HANT"),
                               ("yue-Hant", "guides_yue_hant.py", "YUE_HANT")):
        have = [s for s in order if s in data[lang]]
        body = HEADER % {"desc": DESC[lang], "code": lang,
                         "glossary": GLOSSARY[lang], "upper": upper}
        body += render(data[lang], have)
        io.open(os.path.join(HERE, fname), "w", encoding="utf-8").write(body)
        print("wrote scripts/%s (%d guides)" % (fname, len(have)))


if __name__ == "__main__":
    main()

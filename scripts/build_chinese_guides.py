#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Assemble the three Chinese guide modules from the translated JSON batches.

The 37 guides are written by hand in two variants and derived into a third:

    zh-Hans   Simplified Mandarin — written from the English source
    yue-Hant  Traditional Cantonese — written from the English source, in
              written Cantonese (嘅/係/喺/唔/咗/啲/佢/冇/畀), not Mandarin
    zh-Hant   Traditional Mandarin — OpenCC s2twp over zh-Hans

zh-Hant is derived rather than written because s2twp is a *phrase* conversion:
it does the Taiwan vocabulary swaps (软件→軟體, 数据库→資料庫, 网络→網路) that a
character-by-character conversion misses, and Traditional Mandarin differs from
Simplified Mandarin in nothing else. Cantonese is a different matter — it is a
different language in the grammar and the function words, so no converter
produces it and it is written out in full.

Reads scratch JSON batches (one per guide, `{lang: {slug: {...}}}`) and writes
scripts/guides_zh_hans.py, guides_zh_hant.py and guides_yue_hant.py.

Usage:  python3 scripts/build_chinese_guides.py <batch-dir>
"""
import glob
import io
import json
import os
import re
import sys

import opencc

HERE = os.path.dirname(os.path.abspath(__file__))
CONV = opencc.OpenCC("s2twp")

# ── Why the conversion is not just `CONV.convert(text)` ───────────────────
#
# s2twp is a *phrase* profile, and on this copy it made two kinds of mistake
# that no test and no page load would ever have caught:
#
#   项目 → 專案      right for a software project, wrong for "item", which is
#                    what every one of these guides means by it
#   合并 → 合並      only sometimes: OpenCC's segmenter occasionally swallows
#                    the 并 into the preceding characters and converts it as a
#                    standalone word, so the site's single most important verb
#                    came out two different ways on the same page
#
# So the vocabulary that carries meaning is pinned by hand and hidden from the
# converter behind placeholders; OpenCC only ever sees ordinary prose. TERMS is
# the contract, BANNED is the check that the contract held.
TERMS = {
    # the glossary — these must never be left to a segmenter
    "合并": "合併", "备份": "備份", "笔记": "筆記", "标注": "標註",
    "书签": "書籤", "标签": "標籤", "设备": "裝置", "还原": "還原",
    "浏览器": "瀏覽器", "数据库": "資料庫", "冲突审阅": "衝突檢視",
    "重复项": "重複項", "出版物": "出版物", "聚会": "聚會", "大会": "大會",
    "演讲": "演講", "个人研究": "個人研究", "备份和还原": "備份和還原",
    "希伯来语经卷": "希伯來語經卷", "希腊语经卷": "希臘語經卷",
    # ordinary words s2twp gets wrong or leaves alone
    "项目": "項目", "并排": "並排", "合并前": "合併前", "合并后": "合併後",
    "台设备": "台裝置", "两台": "兩台", "每台": "每台", "一台": "一台",
    "三台": "三台", "哪台": "哪台", "那台": "那台", "这台": "這台",
    # Taiwan vocabulary s2twp gets right but which must survive protection
    "文件": "檔案", "文件夹": "資料夾", "软件": "軟體", "网络": "網路",
    "视频": "影片", "音频": "音訊", "默认": "預設", "设置": "設定",
    "应用程序": "應用程式", "应用": "應用程式",
    "通过": "透過", "发送": "傳送", "屏幕": "螢幕",
    "存储": "儲存", "缓存": "快取", "字节": "位元組", "兆字节": "MB",
}
# Longest first, so "备份和还原" wins over "备份" and "合并前" over "合并".
_TERMS_ORDER = sorted(TERMS, key=len, reverse=True)

# s2twp writes 台 as 臺 everywhere — the form Taiwan's ministries use and
# almost nobody writes on the web, and wrong outright for the Hong Kong reader
# this script also serves. It is a single character with no ambiguity, so it is
# fixed after conversion rather than pinned as a term.
POST = {"臺": "台"}

# Forms that must never appear in the generated Traditional module. Each one is
# a mistake this pipeline actually made; the list only ever grows.
#
# 文件 is deliberately *not* here. As the Simplified word for "file" it must
# become 檔案, which TERMS guarantees — but s2twp also converts 文档 to 文件,
# which is the correct Traditional name for the Documents folder. Banning the
# string would fail the build on a correct page.
BANNED = ["專案", "合並", "臺", "設備", "軟件", "數據庫", "網絡", "視頻"]

# Characters that have no business in Chinese copy. A Cyrillic "материал" once
# reached a Cantonese paragraph and reads as a plausible word at a glance —
# nothing downstream would have objected, so the check lives here.
STRAY = re.compile("[\u0400-\u04FF\u0590-\u06FF\u0E00-\u0E7F"
                   "\uAC00-\uD7AF\u3040-\u30FF]")

